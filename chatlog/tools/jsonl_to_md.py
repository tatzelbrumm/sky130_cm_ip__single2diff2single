"""Convert a Claude Code session transcript (JSONL) into a readable Markdown chat log.

Kept: user messages, assistant text, tool calls (name and the inputs that say what was done), tool results
(shortened), harness notifications (marked as such). Left out: the model's internal reasoning ("thinking"
blocks), injected <system-reminder> blocks, and e-mail addresses other than an allow-list.

usage: python3 jsonl_to_md.py <transcript.jsonl> <out.md> [title]
"""
import json
import re
import sys

ALLOWED_MAIL = {"noreply@anthropic.com", "chipalooza@opencircuitdesign.com"}
MAIL = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
SYSREM = re.compile(r"<system-reminder>.*?</system-reminder>", re.S)
RESULT_MAX = 1500


def clean(text):
    text = SYSREM.sub("", text)
    text = MAIL.sub(lambda m: m.group(0) if m.group(0) in ALLOWED_MAIL else "[e-mail redacted]", text)
    text = re.sub(r"claude-(opus|sonnet|haiku|fable)-[0-9-]+", "[model id]", text)
    return text.strip()


def fence(text, lang=""):
    text = text.replace("```", "ʼʼʼ")
    return f"```{lang}\n{text}\n```"


def short(text, n=RESULT_MAX):
    return text if len(text) <= n else text[:n] + f"\n… [{len(text) - n} more characters cut]"


def tool_call(b):
    name, inp = b.get("name", "?"), b.get("input", {}) or {}
    out = [f"**Tool call: `{name}`**"]
    if "description" in inp:
        out.append(f"_{clean(str(inp['description']))}_")
    if name == "Bash":
        out.append(fence(clean(inp.get("command", "")), "bash"))
    elif name in ("Write",):
        out.append(f"file: `{inp.get('file_path')}`")
        out.append(fence(short(clean(inp.get("content", "")), 4000)))
    elif name in ("Edit",):
        out.append(f"file: `{inp.get('file_path')}`")
        out.append("old:\n" + fence(short(clean(inp.get("old_string", "")), 1500)))
        out.append("new:\n" + fence(short(clean(inp.get("new_string", "")), 1500)))
    elif name == "Agent":
        out.append(fence(clean(inp.get("prompt", ""))))
    else:
        rest = {k: v for k, v in inp.items() if k != "description"}
        if rest:
            out.append(fence(short(clean(json.dumps(rest, ensure_ascii=False, indent=1)), 3000), "json"))
    return "\n\n".join(out)


def tool_result(b):
    c = b.get("content")
    if isinstance(c, list):
        c = "\n".join(x.get("text", "[" + x.get("type", "?") + "]") for x in c if isinstance(x, dict))
    c = clean(str(c or ""))
    return "**Tool result:**\n\n" + fence(short(c)) if c else ""


def main(src, dst, title):
    lines = [f"# {title}", "", f"Generated by `chatlog/tools/jsonl_to_md.py` from the session transcript `{src.split('/')[-1]}`.",
             "Internal reasoning, injected system reminders and private e-mail addresses are left out; tool results are shortened.", ""]
    for raw in open(src, encoding="utf-8"):
        try:
            d = json.loads(raw)
        except ValueError:
            continue
        t = d.get("type")
        if t not in ("user", "assistant"):
            continue
        ts = d.get("timestamp", "")[:19].replace("T", " ")
        m = d.get("message") or {}
        c = m.get("content")
        blocks = [{"type": "text", "text": c}] if isinstance(c, str) else (c or [])
        parts = []
        for b in blocks:
            if not isinstance(b, dict):
                continue
            bt = b.get("type")
            if bt == "thinking" or bt == "redacted_thinking":
                continue
            if bt == "text":
                txt = clean(b.get("text", ""))
                if not txt:
                    continue
                if t == "user" and ("<task-notification>" in txt or txt.startswith("[SYSTEM NOTIFICATION")
                                    or "Monitor event" in txt):
                    parts.append("_Harness notification:_\n\n" + fence(short(txt, 800)))
                elif t == "user":
                    parts.append(txt)
                else:
                    parts.append(txt)
            elif bt == "image":
                parts.append("[image attached by the user]")
            elif bt == "tool_use":
                parts.append(tool_call(b))
            elif bt == "tool_result":
                r = tool_result(b)
                if r:
                    parts.append(r)
        if not parts:
            continue
        who = "Assistant" if t == "assistant" else ("Tool results / harness" if all(
            isinstance(b, dict) and b.get("type") == "tool_result" for b in blocks) else "User (or harness)")
        lines.append(f"## {who} — {ts} UTC")
        lines.append("")
        lines.append("\n\n".join(parts))
        lines.append("")
    open(dst, "w", encoding="utf-8").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else "Chat log")
