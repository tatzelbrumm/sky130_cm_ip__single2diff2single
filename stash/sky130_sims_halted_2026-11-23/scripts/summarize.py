def smoke():
    d = SIM_DIR / "smoke"
    r = results(d / "smoke.log")
    devs = [("nfet_g5v0d10v5", "10/1", "3.3"), ("pfet_g5v0d10v5", "10/1", "3.3"),
            ("nfet_01v8", "1/0.15", "1.8"), ("pfet_01v8", "1/0.15", "1.8")]
    fig, axs = plt.subplots(1, 2, figsize=(8.4, 3.3))
    rows = []
    for i, (dev, wl, vds) in enumerate(devs):
        a = load(d / f"smoke_{dev}.txt")
        ax = axs[0 if "g5v0" in dev else 1]
        ax.semilogy(a["vgs"], np.abs(a["id"]) + 1e-15, color=C[i % 2], label=f"{dev} W/L={wl}")
        ion = float(np.interp(float(vds), a["vgs"], np.abs(a["id"])))
        rows.append(f"| sky130_fd_pr__{dev} | {wl} | {vds} | {float(r['vt_' + dev]):.3f} | "
                    f"{ion * 1e6:.1f} |")
    for ax, t in zip(axs, ("g5v0d10v5 (5 V oxide), |Vds| = 3.3 V", "01v8 (core), |Vds| = 1.8 V")):
        ax.set_title(t, fontsize=9)
        ax.set_xlabel("|Vgs| / V")
        ax.set_ylabel("|Id| / A")
        ax.set_ylim(1e-13, 1e-2)
        ax.legend(fontsize=7, loc="lower right")
    fig.suptitle("sky130 smoke test, tt, 27 C (" + LABEL + ")", fontsize=8)
    savefig(fig, "smoke_idvgs.png")
    md = header("Smoke test: sky130 MOS Id-Vgs, tt, 27 C") + [
        "Deck: `verification/decks/tb_smoke.spice` (corner section `tt`, 27 C). Plot: "
        "`smoke_idvgs.png`.", "",
        "Vt_cc = constant-current threshold |Vgs| at |Id| = 100 nA x W/L (interpolated, 10 mV sweep "
        "step). Id(on) = |Id| at |Vgs| = |Vds|.", "",
        "| device | W/L (um) | abs(Vds) (V) | Vt_cc (V) | Id(on) (uA) |", "|---|---|---|---|---|",
        *rows, "",
        "Meaning: the models load and give plausible thresholds; the 5 V-oxide (g5v0d10v5) devices "
        "used for the 3.3 V references have |Vt| ~ 0.76 V (n) and ~ 1.0 V (p). The high PMOS |Vt| is "
        "why the IHP two-diode PMOS stacks were replaced by self-cascodes (see the netlists).",
        "Not shown: corners, temperature, mismatch, model validity beyond Id-Vgs."]
    (RES / "smoke.md").write_text("\n".join(md) + "\n")
