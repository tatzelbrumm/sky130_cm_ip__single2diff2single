# ---------------------------------------------------------------- helpers
def versions():
    v = {}
    try:
        out = subprocess.run([os.environ.get("NGSPICE", "ngspice"), "-v"], capture_output=True,
                             text=True).stdout
        m = re.search(r"(ngspice-\S+).*?Creation Date:\s*([^\n*]+)", out, re.S)
        v["ngspice"] = f"{m.group(1)} (build {m.group(2).strip()})" if m else out.strip()[:80]
    except OSError:
        v["ngspice"] = "unknown"
    src = Path(PDK_ROOT, PDK, "SOURCES")
    v["pdk"] = f"{PDK} at {PDK_ROOT}; SOURCES: " + (" ".join(src.read_text().split())
                                                      if src.exists() else "n/a")
    ni = Path(PDK_ROOT, PDK, ".config/nodeinfo.json")
    if ni.exists():
        try:
            v["sky130_fd_pr"] = json.loads(ni.read_text())["reference"]["primitive"]["sky130_fd_pr"]
        except Exception:  # noqa: BLE001
            try:
                v["sky130_fd_pr"] = json.loads(ni.read_text())["primitive"]["sky130_fd_pr"]
            except Exception:  # noqa: BLE001
                pass
    v["python/matplotlib"] = f"{sys.version.split()[0]} / {matplotlib.__version__}"
    return v


def header(title):
    v = versions()
    lines = [f"<!--\nSPDX-FileCopyrightText: 2026 Christoph Maier\nSPDX-License-Identifier: Apache-2.0\n-->",
             f"# {title}", "", f"**{LABEL}.**", "",
             "Tools: " + "; ".join(f"{k}: `{val}`" for k, val in v.items()) + ".",
             "Model library: `$PDK_ROOT/sky130A/libs.tech/ngspice/sky130.lib.spice`. "
             "Generated by `verification/scripts/summarize.py` from runs of "
             "`verification/run_all.sh`.", ""]
    return lines


def load(path):
    """wrdata file with header row (wr_singlescale, wr_vecnames) -> dict of arrays."""
    with open(path) as fh:
        names = fh.readline().split()
    d = np.loadtxt(path, skiprows=1, ndmin=2)
    return {n: d[:, i] for i, n in enumerate(names)}


def results(log):
    r = {}
    for line in Path(log).read_text(errors="replace").splitlines():
        m = re.match(r"\s*RESULT\s+(\S+)(?:\s+gmin)?\s*=\s*(\S+)", line)
        if m:
            r[m.group(1)] = m.group(2)
        m = re.match(r"\s*(vt_\S+)\s*=\s*(\S+)", line)
        if m:
            r[m.group(1)] = m.group(2)
    return r


def physical(d, vdd):
    """True where every saved internal node voltage is within -0.2 V .. vdd + 0.2 V."""
    ok = np.ones(len(d["iout"]), bool)
    for k, a in d.items():
        if k.startswith("v(") and k != "v-sweep":
            hi = d["v-sweep"] if "v-sweep" in d else vdd
            ok &= (a > -0.2) & (a < hi + 0.2)
    return ok


def fmt(x, unit="uA", scale=1e6, nd=3):
    return f"{x * scale:.{nd}f} {unit}"


def split_sec(sec):
    if sec in ("ll", "hh"):
        return "tt", sec
    if "_" in sec:
        a, b = sec.split("_")
        return a, b
    return sec, ""


def savefig(fig, name):
    p = RES / name
    fig.savefig(p, dpi=110, bbox_inches="tight")
    plt.close(fig)
    kb = p.stat().st_size / 1024
    assert kb < 300, f"{p} is {kb:.0f} kB"
    return p


