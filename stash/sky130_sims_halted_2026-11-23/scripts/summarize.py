# ---------------------------------------------------------------- reference DC + tran
def ref_summary(ref, title, secs):
    dcd, trd = SIM_DIR / f"{ref}_dc", SIM_DIR / f"{ref}_tran"
    I = {}            # (sec, T, vdd) -> iout from the upward temperature sweep
    IDD = {}
    curves = {}       # (sec, vdd) -> (T, I)
    updown = 0.0
    glitches = []
    nrej = 0
    for sec in secs:
        for v in VDDS:
            tag = f"{v:.1f}".replace(".", "p")
            up = load(dcd / f"{ref}_{sec}_temp_v{tag}.txt")
            dn = load(dcd / f"{ref}_{sec}_tempdn_v{tag}.txt")
            T = up["temp-sweep"]
            ph_up, ph_dn = physical(up, v), physical(dn, v)[::-1]
            iup, idn = up["iout"], dn["iout"][::-1]
            assert np.allclose(dn["temp-sweep"][::-1], T)
            nrej += int((~ph_up).sum() + (~ph_dn).sum())
            for k in range(len(T)):
                if not (ph_up[k] or ph_dn[k]):
                    glitches.append((sec, v, T[k]))
            both = ph_up & ph_dn
            if both.any():
                rel = np.abs(iup[both] - idn[both]) / np.abs(iup[both])
                updown = max(updown, float(rel.max()))
            i = np.where(ph_up, iup, np.where(ph_dn, idn, np.nan))
            idd = np.where(ph_up, up["idd"], dn["idd"][::-1])
            curves[(sec, v)] = (T, i)
            for t in TEMPS:
                k = int(np.argmin(np.abs(T - t)))
                I[(sec, t, v)] = float(i[k])
                IDD[(sec, t, v)] = float(idd[k])
    nom = I[("tt", 27, 3.3)]
    allv = list(I.items())
    imin = min(allv, key=lambda kv: kv[1])
    imax = max(allv, key=lambda kv: kv[1])

    # supply sensitivity (3.0 -> 3.6 V), per section and temperature
    sens = {(s, t): (I[(s, t, 3.6)] - I[(s, t, 3.0)]) / (0.6 * I[(s, t, 3.3)]) * 100
            for s in secs for t in TEMPS}
    # temperature coefficient at 3.3 V: box method over -40..125 C, and end-point average
    tcbox, tcavg = {}, {}
    for s in secs:
        for v in VDDS:
            T, i = curves[(s, v)]
            i27 = float(np.interp(27, T[~np.isnan(i)], i[~np.isnan(i)]))
            tcbox[(s, v)] = (np.nanmax(i) - np.nanmin(i)) / (i27 * 165) * 1e6
            tcavg[(s, v)] = (i[-1] - i[0]) / (i27 * 165) * 1e6
    # minimum supply: lowest vdd from which iout stays within 1 % of its 3.3 V value
    vmin = {}
    nrej_v = [0]
    for s in secs:
        for t, tg in zip(TEMPS, ("tm40", "t27", "t125")):
            a = load(dcd / f"{ref}_{s}_vdd_{tg}.txt")
            ph = physical(a, None)
            nrej_v[0] += int((~ph).sum())
            vv, ii = a["v-sweep"][ph], a["iout"][ph]
            i33 = float(np.interp(3.3, vv, ii))
            bad = np.where(np.abs(ii - i33) > 0.01 * abs(i33))[0]
            vmin[(s, t)] = float(vv[bad[-1] + 1]) if len(bad) and bad[-1] + 1 < len(vv) else float(vv[0])
    # disabled state
    dis_i, dis_dd = [], []
    for s in secs:
        r = results(dcd / f"{ref}_{s}.log")
        for tg in ("tm40", "t27", "t125"):
            dis_i.append(abs(float(r[f"dis_iout_{tg}"])))
            dis_dd.append(abs(float(r[f"dis_idd_{tg}"])))

    # start-up transients
    st_rows, st_fail, gm_retry, worst_ratio, worst_t = [], [], [], (None, 1.0), (None, 0.0)
    ntran = 0
    for s in secs:
        r = results(trd / f"{ref}_{s}.log")
        for t in TEMPS:
            for v in (3.0, 3.6):
                for sp, tr in (("fast", 10e-6), ("slow", 1e-3)):
                    key = f"tran_{sp}_t{t}_v{v:.1f}"
                    gm = r.get(key, "missing")
                    if gm != "1e-12":
                        gm_retry.append(f"{s} {sp} {t} C {v} V: gmin {gm}")
                    if gm in ("missing", "FAILED"):
                        st_fail.append(f"{s} {sp} {t} C {v} V: simulation did not finish")
                        continue
                    ntran += 1
                    a = load(trd / f"{ref}_{s}_{sp}_t{t}_v{v:.1f}.txt")
                    tt_, ii = a["time"], a["iout"]
                    tend = tt_[-1]
                    fin = float(np.mean(ii[tt_ > 0.95 * tend]))
                    dc = I[(s, t, v)]
                    ratio = fin / dc
                    # settling: last time |i - fin| > 1 % of fin
                    out = np.where(np.abs(ii - fin) > 0.01 * abs(fin))[0]
                    tset = float(tt_[out[-1] + 1]) if len(out) and out[-1] + 1 < len(tt_) else 0.0
                    after = tset - tr  # relative to the end of the supply ramp
                    if not (0.95 < ratio < 1.05) or tset > 0.9 * tend:
                        st_fail.append(f"{s} {sp} {t} C {v} V: final {fin*1e6:.3f} uA vs DC "
                                       f"{dc*1e6:.3f} uA, settled {tset*1e6:.2f} us")
                    if abs(ratio - 1) > abs(worst_ratio[1] - 1):
                        worst_ratio = (f"{s} {sp} {t} C {v} V", ratio)
                    if after > worst_t[1]:
                        worst_t = (f"{s} {sp} {t} C {v} V", after)

    # ---------------- plots
    fig, axs = plt.subplots(1, 2, figsize=(9.6, 3.6), sharey=True)
    for s in secs:
        m, rc = split_sec(s)
        axs[0].plot(*[(x if j == 0 else x * 1e6) for j, x in enumerate(curves[(s, 3.3)])],
                    color=MOS_COLOR[m], ls=RES_STYLE[rc], label=s)
    axs[0].set_title("iout vs temperature, vdd = 3.3 V, all sections", fontsize=9)
    axs[0].set_xlabel("T / C")
    axs[0].set_ylabel("iout / uA (into 0.7 V)")
    axs[0].legend(fontsize=6.5, ncol=3)
    for j, v in enumerate(VDDS):
        T, i = curves[("tt", v)]
        axs[1].plot(T, i * 1e6, color=C[j], label=f"tt, vdd = {v} V")
    for t in TEMPS:
        pass
    axs[1].set_title("tt, vdd = 3.0 / 3.3 / 3.6 V", fontsize=9)
    axs[1].set_xlabel("T / C")
    axs[1].legend(fontsize=7)
    fig.suptitle(f"{title}: DC ({LABEL})", fontsize=8)
    savefig(fig, f"{ref}_temp.png")

    fig, axs = plt.subplots(1, 3, figsize=(10.5, 3.2), sharey=True)
    for ax, m in zip(axs, ("tt", "ss", "ff")):
        for t, tg in zip(TEMPS, ("tm40", "t27", "t125")):
            a = load(dcd / f"{ref}_{m}_vdd_{tg}.txt")
            ph = physical(a, None)
            ax.plot(a["v-sweep"][ph], a["iout"][ph] * 1e6, color=TCOL[t], label=f"{t} C")
        ax.set_title(f"{m}: iout vs vdd", fontsize=9)
        ax.set_xlabel("vdd / V")
        ax.set_ylim(-0.5, max(8, imax[1] * 1.3e6))
        ax.axvspan(3.0, 3.6, color="#e3e2de", alpha=0.5, lw=0)
    axs[0].set_ylabel("iout / uA (into 0.7 V)")
    axs[0].legend(fontsize=7, loc="upper left")
    fig.suptitle(f"{title}: supply sweep, shaded = 3.0..3.6 V ({LABEL})", fontsize=8)
    savefig(fig, f"{ref}_vdd.png")

    fig, axs = plt.subplots(1, 2, figsize=(9.6, 3.4), sharey=True)
    for ax, (t, v) in zip(axs, ((-40, 3.0), (125, 3.6))):
        for s in secs:
            m, rc = split_sec(s)
            f = trd / f"{ref}_{s}_fast_t{t}_v{v:.1f}.txt"
            if f.exists():
                a = load(f)
                ax.plot(a["time"] * 1e6, a["iout"] * 1e6, color=MOS_COLOR[m], ls=RES_STYLE[rc],
                        label=s, lw=1.2)
        ax.set_title(f"start-up, vdd ramp 0 -> {v} V in 10 us, {t} C", fontsize=9)
        ax.set_xlabel("t / us")
    axs[0].set_ylabel("iout / uA (NMOS diode load)")
    axs[0].legend(fontsize=6.5, ncol=3)
    fig.suptitle(f"{title}: start-up transients ({LABEL})", fontsize=8)
    savefig(fig, f"{ref}_startup.png")

    # ---------------- markdown
    def cond(k):
        s, t, v = k
        return f"{s}, {t} C, {v} V"

    def mm(d, absval=False):
        it = list(d.items())
        f = (lambda kv: abs(kv[1])) if absval else (lambda kv: kv[1])
        lo, hi = min(it, key=f), max(it, key=f)
        return lo, hi

    sl, sh = mm(sens)
    s_tt = sens[("tt", 27)]
    tb_l, tb_h = mm({k: v for k, v in tcbox.items() if k[1] == 3.3})
    ta_l, ta_h = mm({k: v for k, v in tcavg.items() if k[1] == 3.3})
    vm_l, vm_h = mm(vmin)
    idd_nom = IDD[("tt", 27, 3.3)]
    idd_l, idd_h = mm({k: v for k, v in IDD.items()})
    md = header(title) + [
        f"Netlist: `verification/netlists/{ref}_core_sky130.spice`. Decks: "
        "`verification/decks/tb_ref_dc.spice`, `verification/decks/tb_ref_tran.spice`. Plots: "
        f"`{ref}_temp.png`, `{ref}_vdd.png`, `{ref}_startup.png`.", "",
        "Conditions: vdd 3.0 / 3.3 / 3.6 V; T -40 / 27 / 125 C (DC temperature sweeps in 5 C steps); "
        f"library sections: {', '.join(secs)}. "
        + ("MOS/BJT corner tt/ss/ff/sf/fs, each with resistor corner typical / `_ll` (res_low) / "
           "`_hh` (res_high); in `sky130.lib.spice` `ll`/`hh` = tt MOS with low/high R and C. "
           "For sky130_fd_pr__res_xhigh_po the res corner is var_mult = -/+ 0.15 (R -/+ 15 %, "
           "plus a TC shift). The vertical PNP model parameters (dkispp5x, dkbfpp5x) follow the "
           "MOS corner file (ss/ff change Is and beta; tt/sf/fs identical)."
           if ref == "bg" else
           "MOS corners only (the core has no resistor or BJT, so resistor corners do not apply).")
        + " Load: iout sources into an ideal 0.7 V source (DC) or an NMOS diode "
        "nfet_g5v0d10v5 20/1 (start-up transients). Enabled: en_3v3 = vdd, en_3v3_b = 0.", "",
        "## Summary (min / typ / max)", "",
        "| quantity | min | typ (tt, 27 C, 3.3 V) | max | notes |", "|---|---|---|---|---|",
        f"| iout, all sections x T x vdd | {fmt(imin[1])} ({cond(imin[0])}) | {fmt(nom)} | "
        f"{fmt(imax[1])} ({cond(imax[0])}) | spread {imin[1]/nom*100-100:+.1f} % / "
        f"{imax[1]/nom*100-100:+.1f} % vs typ |",
        f"| supply sensitivity (I(3.6)-I(3.0))/(0.6 V * I(3.3)) | {sl[1]:+.3f} %/V ({sl[0][0]}, "
        f"{sl[0][1]} C) | {s_tt:+.3f} %/V | {sh[1]:+.3f} %/V ({sh[0][0]}, {sh[0][1]} C) | per "
        "section and T |",
        f"| TC, box (max-min)/(I27*165 K), 3.3 V | {tb_l[1]:.0f} ppm/K ({tb_l[0][0]}) | "
        f"{tcbox[('tt', 3.3)]:.0f} ppm/K | {tb_h[1]:.0f} ppm/K ({tb_h[0][0]}) | -40..125 C |",
        f"| TC, end points (I125-I-40)/(I27*165 K), 3.3 V | {ta_l[1]:+.0f} ppm/K ({ta_l[0][0]}) | "
        f"{tcavg[('tt', 3.3)]:+.0f} ppm/K | {ta_h[1]:+.0f} ppm/K ({ta_h[0][0]}) | sign = slope |",
        f"| min. vdd for iout within 1 % of I(3.3 V) | {vm_l[1]:.2f} V ({vm_l[0][0]}, {vm_l[0][1]} C)"
        f" | {vmin[('tt', 27)]:.2f} V | {vm_h[1]:.2f} V ({vm_h[0][0]}, {vm_h[0][1]} C) | DC supply "
        "sweep, 10 mV steps |",
        f"| supply current enabled (incl. iout) | {fmt(idd_l[1])} ({cond(idd_l[0])}) | {fmt(idd_nom)} "
        f"| {fmt(idd_h[1])} ({cond(idd_h[0])}) | |",
        f"| iout disabled, 3.6 V | | | {max(dis_i)*1e12:.1f} pA | at the resolution of the 1 Tohm "
        "rshunt numerical aid; real leakage not resolved |",
        f"| supply current disabled, 3.6 V | | | {max(dis_dd)*1e9:.2f} nA | includes ~3.6 pA per node "
        "from rshunt |",
        "", "## iout per section (uA, into 0.7 V)", "",
        "| section | " + " | ".join(f"{t} C / {v} V" for t in TEMPS for v in VDDS) + " |",
        "|---|" + "---|" * 9]
    for s in secs:
        md.append(f"| {s} | " + " | ".join(f"{I[(s, t, v)]*1e6:.3f}" for t in TEMPS for v in VDDS)
                  + " |")
    md += ["", "## Start-up (supply-ramp transients)", "",
           f"{ntran} transients finished: {len(secs)} sections x T (-40 / 27 / 125 C) x final vdd "
           "(3.0 / 3.6 V) x ramp (10 us and 1 ms, simulated to 3x the ramp). Pass = mean iout over "
           "the last 5 % within +-5 % of the DC value at the same section/T/vdd (DC load 0.7 V, "
           "transient load NMOS diode, so a small difference is expected) and settled to 1 % "
           "before 90 % of the run.", "",
           f"- failures: **{len(st_fail)}**" + ("" if not st_fail else ": " + "; ".join(st_fail)),
           f"- largest |final/DC - 1|: {abs(worst_ratio[1]-1)*100:.2f} % ({worst_ratio[0]})",
           f"- longest settling to 1 % after the end of the ramp: {worst_t[1]*1e6:.2f} us "
           f"({worst_t[0]})",
           f"- runs that needed a gmin retry (numerics in the first ns, vdd ~ 0): {len(gm_retry)}"
           + ("" if not gm_retry else " (" + "; ".join(gm_retry) + ")"), "",
           "## Numerical checks", "",
           f"- DC temperature sweeps run upward and downward: largest relative difference "
           f"{updown*100:.4f} % (a jump to another DC solution would show here).",
           f"- non-physical DC points (an internal node outside -0.2 V .. vdd + 0.2 V; spurious "
           f"solutions, see netlist note) rejected: {nrej} of {len(secs) * 3 * 2 * 34} "
           f"temperature-sweep points (each T is taken from the other sweep direction), "
           f"{nrej_v[0]} of {len(secs) * 3 * 361} supply-sweep points (dropped); temperatures "
           f"with no physical point in either direction: {len(glitches)}"
           + ("" if not glitches else " " + str(glitches[:10])), ""]
    return md, dict(nom=nom, imin=imin, imax=imax)


def ref_md(ref):
    if ref == "bg":
        title = "Banba bandgap current reference core (bg_core_sky130)"
        secs = []
