"""Write the ngspice decks of verification/pads/decks/ for the sky130 ports of the custom-pad cores.

sky130 pre-layout schematic simulation (feasibility, not sign-off).

The decks are generated so that the PDK location is a variable: the .lib line is written from
$PDK_ROOT (default /foss/pdks) at generation time. Every deck is self-contained and unrolled
(one explicit analysis + wrdata line per condition), so the deck that produced a number is the
file in decks/. Data files go to ../build/ (relative to decks/, git-ignored).
Run from anywhere:  PDK_ROOT=/path/to/pdks python3 scripts/gen_decks.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PADS = os.path.dirname(HERE)
DECKS = os.path.join(PADS, "decks")
PDK_ROOT = os.environ.get("PDK_ROOT", "/foss/pdks")
LIB = os.path.join(PDK_ROOT, "sky130A", "libs.tech", "ngspice", "sky130.lib.spice")

LABEL = "sky130 pre-layout schematic simulation (feasibility, not sign-off)"
CORNERS = ["tt", "ss", "ff", "sf", "fs"]
TEMPS = [-40, 27, 125]
VDDS = [3.0, 3.3, 3.6]

# --- S2D conditions
S2D_VREF = 0.49                  # pad reference (pad_ref_rb nominal)
S2D_VCM_IHP = 1.26               # internal common mode (pad_ref_rb nominal)
S2D_VCM_SWEEP = [round(0.80 + 0.05 * i, 2) for i in range(13)] + [S2D_VCM_IHP]   # 0.80 .. 1.40, + 1.26
S2D_VCM_PORT = float(os.environ.get("S2D_VCM_PORT", "1.05"))   # vcm used for AC / summary (window centre)
S2D_VREF_SWEEP = [0.40, 0.45, 0.49, 0.55, 0.60]   # IHP replica vref spread 0.436 .. 0.596 V
S2D_CLOAD = 0.5e-12              # external load per output (IHP default), on top of the built-in MIM

# --- D2S conditions
D2S_VREF_IHP = 1.26              # D2S vref = S2D vcm (pad_ref_rb: one vcm line serves both)
D2S_VREF_SWEEP = [round(0.90 + 0.10 * i, 2) for i in range(7)] + [D2S_VREF_IHP]   # 0.90 .. 1.50, + 1.26
D2S_VREF_PORT = float(os.environ.get("D2S_VREF_PORT", "1.05"))
D2S_CLOADS = [10e-12, 100e-12, 300e-12]


def header(title, includes):
    lines = [
        f"* {title}",
        "* SPDX-FileCopyrightText: 2026 Christoph Maier",
        "* SPDX-License-Identifier: Apache-2.0",
        f"* {LABEL}.",
        "* Generated by scripts/gen_decks.py; regenerate rather than edit. Run from decks/: ngspice -b <deck>",
    ]
    return lines, includes


def lib_line(corner):
    return f".lib {LIB} {corner}"


def fmt(x):
    return f"{x:g}"


# ------------------------------------------------------------------ S2D
def s2d_dc(corner):
    """DC transfer pad 0 .. 1 V, all temps / supplies, vcm window sweep (vref fixed)."""
    title = f"s2d_dc_{corner}: S2D core DC transfer, corner {corner}"
    L, _ = header(title, [])
    L += [
        "* Pad (vin) swept 0 .. 1 V in 10 mV steps; vref = %g V; vcm swept for the input/output window." % S2D_VREF,
        "* Ideal 5 uA iref sourced into the bias tree; 0.5 pF external load per output (DC: no effect).",
        lib_line(corner),
        ".include ../netlists/units_sky130.spice",
        ".include ../netlists/s2d_core_sky130.spice",
        "Vdd vdd 0 3.3",
        f"Vref vref 0 {S2D_VREF}",
        f"Vcm vcm 0 {S2D_VCM_IHP}",
        f"Vin vin 0 {S2D_VREF}",
        "Iref vdd iref 5u",
        "X1 vdd 0 vin vref vcm op on iref s2d_core_sky130",
        f"CLp op 0 {S2D_CLOAD}",
        f"CLn on 0 {S2D_CLOAD}",
        ".control",
        "set wr_singlescale",
        "set wr_vecnames",
        "option numdgt=8",
    ]
    for t in TEMPS:
        L.append(f"option temp={t}")
        for v in VDDS:
            L.append(f"alter vdd dc={v}")
            for cm in S2D_VCM_SWEEP:
                L.append(f"alter vcm dc={cm}")
                L.append("dc vin 0 1 0.01")
                fn = f"../build/s2d_dc_{corner}_T{t}_V{fmt(v)}_cm{fmt(cm)}.txt"
                L.append(f"wrdata {fn} v(op) v(on) i(vdd)")
                L.append("destroy all")
    L += [".endc", ".end"]
    return "\n".join(L) + "\n"


def s2d_ac(corner):
    """Closed-loop AC: differential (pad -> outp - outn) and common mode (vcm -> (outp + outn)/2)."""
    title = f"s2d_ac_{corner}: S2D core closed-loop AC, corner {corner}"
    L, _ = header(title, [])
    L += [
        f"* pad = vref = {S2D_VREF} V (mid-scale u = 0), vcm = {S2D_VCM_PORT} V (sky130 port value),",
        "* 0.5 pF external load per output plus the built-in 16 x 16 um MIM.",
        "* Run 1: ac 1 on pad -> vd = v(op) - v(on) (ideal 2).  Run 2: ac 1 on vcm -> vc = (v(op) + v(on))/2 (ideal 1).",
        lib_line(corner),
        ".include ../netlists/units_sky130.spice",
        ".include ../netlists/s2d_core_sky130.spice",
        "Vdd vdd 0 3.3",
        f"Vref vref 0 {S2D_VREF}",
        f"Vcm vcm 0 dc {S2D_VCM_PORT} ac 0",
        f"Vin vin 0 dc {S2D_VREF} ac 1",
        "Iref vdd iref 5u",
        "X1 vdd 0 vin vref vcm op on iref s2d_core_sky130",
        f"CLp op 0 {S2D_CLOAD}",
        f"CLn on 0 {S2D_CLOAD}",
        ".control",
        "set wr_singlescale",
        "set wr_vecnames",
        "option numdgt=8",
    ]
    for t in TEMPS:
        L.append(f"option temp={t}")
        for v in VDDS:
            L.append(f"alter vdd dc={v}")
            L.append("alter @vin[acmag]=1")
            L.append("alter @vcm[acmag]=0")
            L.append("ac dec 40 100 1G")
            L.append("let vd = v(op) - v(on)")
            L.append(f"wrdata ../build/s2d_acd_{corner}_T{t}_V{fmt(v)}.txt mag(vd) ph(vd)")
            L.append("destroy all")
            L.append("alter @vin[acmag]=0")
            L.append("alter @vcm[acmag]=1")
            L.append("ac dec 40 100 1G")
            L.append("let vc = (v(op) + v(on))/2")
            L.append(f"wrdata ../build/s2d_acc_{corner}_T{t}_V{fmt(v)}.txt mag(vc) ph(vc)")
            L.append("destroy all")
            L.append("op")
            L.append(f"wrdata ../build/s2d_op_{corner}_T{t}_V{fmt(v)}.txt v(op) v(on) i(vdd)")
            L.append("destroy all")
    L += [".endc", ".end"]
    return "\n".join(L) + "\n"


def s2d_vref_deck(corner, temp):
    title = f"s2d_vref_{corner}: S2D core DC transfer vs vref, corner {corner}, {temp} C, vcm = {S2D_VCM_PORT} V"
    L, _ = header(title, [])
    L += [
        "* Pad swept 0 .. 1 V (10 mV); vref swept over the IHP replica's spread (0.436 .. 0.596 V over PVT).",
        lib_line(corner),
        ".include ../netlists/units_sky130.spice",
        ".include ../netlists/s2d_core_sky130.spice",
        "Vdd vdd 0 3.3",
        f"Vref vref 0 {S2D_VREF}",
        f"Vcm vcm 0 {S2D_VCM_PORT}",
        f"Vin vin 0 {S2D_VREF}",
        "Iref vdd iref 5u",
        "X1 vdd 0 vin vref vcm op on iref s2d_core_sky130",
        f"CLp op 0 {S2D_CLOAD}",
        f"CLn on 0 {S2D_CLOAD}",
        ".control", "set wr_singlescale", "set wr_vecnames", "option numdgt=8", f"option temp={temp}",
    ]
    for v in VDDS:
        L.append(f"alter vdd dc={v}")
        for vr in S2D_VREF_SWEEP:
            L.append(f"alter vref dc={vr}")
            L.append("dc vin 0 1 0.01")
            L.append(f"wrdata ../build/s2d_vref_{corner}_T{temp}_V{fmt(v)}_vr{fmt(vr)}.txt v(op) v(on) i(vdd) v(vref)")
            L.append("destroy all")
    L += [".endc", ".end"]
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ D2S
def d2s_common(corner, vref, extra):
    return [
        lib_line(corner),
        ".include ../netlists/units_sky130.spice",
        ".include ../netlists/d2s_core_sky130.spice",
        "Vdd vdd 0 3.3",
        f"Vref vref 0 {vref}",
        "Vd vd 0 0",
        "* vinp = vref + vd/2, vinn = vref - vd/2 (input CM = vref = vcm line)",
        "Ep vinp vref vd 0 0.5",
        "En vinn vref vd 0 -0.5",
        "Iref vdd iref 5u",
        "X1 vdd 0 vinp vinn vref pad iref d2s_core_sky130",
    ] + extra


def d2s_dc(corner):
    """DC transfer vd = -1 .. 1 V, unloaded and 1 kOhm to vref, all temps / supplies, vref sweep."""
    title = f"d2s_dc_{corner}: D2S core DC transfer, corner {corner}"
    L, _ = header(title, [])
    L += [
        "* vd = vinp - vinn swept -2 .. +2 V in 20 mV steps (INL over +-1 V, swing over +-2 V), input CM = vref;",
        "* ideal pad - vref = vd/2.",
        "* Load: Rl (1 kOhm or 1 GOhm = unloaded) from pad to vref (load termination at the reference).",
        "* vref swept for the window; ideal 5 uA iref.",
    ]
    L += d2s_common(corner, D2S_VREF_IHP, ["Rl pad vref 1k", "Cl pad 0 100p"])
    L += [".control", "set wr_singlescale", "set wr_vecnames", "option numdgt=8"]
    for t in TEMPS:
        L.append(f"option temp={t}")
        for v in VDDS:
            L.append(f"alter vdd dc={v}")
            for vr in D2S_VREF_SWEEP:
                L.append(f"alter vref dc={vr}")
                for rl, tag in ((1e3, "r1k"), (1e9, "open")):
                    L.append(f"alter rl {rl:g}")
                    L.append("dc vd -2 2 0.02")
                    fn = f"../build/d2s_dc_{corner}_T{t}_V{fmt(v)}_vr{fmt(vr)}_{tag}.txt"
                    L.append(f"wrdata {fn} v(pad) v(vref) i(vdd) @m.x1.xa.xop.msky130_fd_pr__pfet_g5v0d10v5[id] @m.x1.xa.xon.msky130_fd_pr__nfet_g5v0d10v5[id]")
                    L.append("destroy all")
    L += [".endc", ".end"]
    return "\n".join(L) + "\n"


def d2s_ac(corner):
    title = f"d2s_ac_{corner}: D2S core closed-loop AC, corner {corner}"
    L, _ = header(title, [])
    L += [
        f"* vd = 0 (dc), ac 1 on vd; vref = {D2S_VREF_PORT} V; load (1 kOhm to vref, or open) || Cl (10 / 100 / 300 pF).",
        "* Ideal |pad / vd| = 0.5 (-6.02 dB).",
    ]
    L += d2s_common(corner, D2S_VREF_PORT, ["Rl pad vref 1k", "Cl pad 0 100p"])
    L[L.index("Vd vd 0 0")] = "Vd vd 0 dc 0 ac 1"
    L += [".control", "set wr_singlescale", "set wr_vecnames", "option numdgt=8"]
    for t in TEMPS:
        L.append(f"option temp={t}")
        for v in VDDS:
            L.append(f"alter vdd dc={v}")
            for rl, tag in ((1e3, "r1k"), (1e9, "open")):
                L.append(f"alter rl {rl:g}")
                for cl in D2S_CLOADS:
                    L.append(f"alter cl {cl:g}")
                    L.append("ac dec 40 100 1G")
                    fn = f"../build/d2s_ac_{corner}_T{t}_V{fmt(v)}_{tag}_cl{cl*1e12:g}p.txt"
                    L.append(f"wrdata {fn} mag(v(pad)) ph(v(pad))")
                    L.append("destroy all")
            L.append("alter rl 1k")
            L.append("op")
            L.append(f"wrdata ../build/d2s_op_{corner}_T{t}_V{fmt(v)}.txt v(pad) i(vdd) @m.x1.xa.xop.msky130_fd_pr__pfet_g5v0d10v5[id] @m.x1.xa.xon.msky130_fd_pr__nfet_g5v0d10v5[id]")
            L.append("destroy all")
    L += [".endc", ".end"]
    return "\n".join(L) + "\n"


def main():
    which = sys.argv[1:] or ["s2d", "d2s"]
    os.makedirs(DECKS, exist_ok=True)
    out = []
    for c in CORNERS:
        if "s2d" in which:
            out += [(f"s2d_dc_{c}.spice", s2d_dc(c)), (f"s2d_ac_{c}.spice", s2d_ac(c))]
        if "d2s" in which:
            out += [(f"d2s_dc_{c}.spice", d2s_dc(c)), (f"d2s_ac_{c}.spice", d2s_ac(c))]
    if "s2d" in which:
        for c, t in (("tt", 27), ("ss", -40), ("ff", 125)):
            out.append((f"s2d_vref_{c}.spice", s2d_vref_deck(c, t)))
    for name, text in out:
        with open(os.path.join(DECKS, name), "w") as f:
            f.write(text)
    print(f"wrote {len(out)} decks to {DECKS} (PDK_ROOT={PDK_ROOT}, S2D vcm {S2D_VCM_PORT}, D2S vref {D2S_VREF_PORT})")


if __name__ == "__main__":
    main()
